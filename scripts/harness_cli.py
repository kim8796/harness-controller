def command_self_uninstall(args: argparse.Namespace) -> int:
    target = _global_shim_path(args.prefix)
    try:
        if not target.exists():
            print("하네스 global wrapper가 설치되어 있지 않습니다.")
            print(f"- path: `{target.as_posix()}`")
            return 0
        if not _is_installed_global_shim(target):
            raise HarnessCliError(f"refusing to remove non-harness file: {target.as_posix()}")
        target.unlink()
        print("하네스 global wrapper 제거 완료")
        print(f"- path: `{target.as_posix()}`")
        return 0
    except HarnessCliError as exc:
        print(f"error: {exc}")
        return 2


