def _shim_dir(raw_prefix: Path) -> Path:
    expanded = raw_prefix.expanduser()
    return expanded if expanded.is_absolute() else (Path.cwd() / expanded).absolute()


def _path_is_relative_to(path: Path, parent: Path) -> bool:
    try:
        path.relative_to(parent)
    except ValueError:
        return False
    return True


def _validate_shim_dir(prefix: Path) -> None:
    resolved_prefix = prefix.resolve()
    for unsafe in UNSAFE_GLOBAL_SHIM_DIRS:
        if resolved_prefix == unsafe or _path_is_relative_to(resolved_prefix, unsafe):
            raise HarnessCliError(f"unsafe global shim prefix: {prefix.as_posix()}")
    if prefix.exists() and prefix.is_symlink():
        raise HarnessCliError(f"refusing symlink prefix: {prefix.as_posix()}")
    if prefix.exists() and not prefix.is_dir():
        raise HarnessCliError(f"global shim prefix is not a directory: {prefix.as_posix()}")


def _global_shim_path(prefix: Path) -> Path:
    return _shim_dir(prefix) / "harness"


def _global_shim_text() -> str:
    return f"""#!/usr/bin/env python3
# {GLOBAL_SHIM_MARKER}
from __future__ import annotations

import os
import sys
from pathlib import Path

MARKER = {GLOBAL_SHIM_MARKER!r}
REQUIRED_LOCAL_FILES = (
    "HARNESS.md",
    "scripts/harness_cli.py",
    "scripts/harness_starter_install.py",
    "scripts/harness_export.py",
    "docs/harness/START_HERE.md",
)


def _is_global_shim(path: Path) -> bool:
    try:
        return MARKER in path.read_text(encoding="utf-8", errors="replace")[:4096]
    except OSError:
        return False


def _is_local_harness_root(directory: Path) -> bool:
    return all((directory / relative).exists() for relative in REQUIRED_LOCAL_FILES)


def _find_local_harness(start: Path) -> Path | None:
    for directory in (start, *start.parents):
        candidate = directory / "harness"
        if not candidate.exists() or not candidate.is_file():
            continue
        if _is_global_shim(candidate):
            continue
        if not _is_local_harness_root(directory):
            continue
        if os.access(candidate, os.X_OK):
            return candidate
    return None


def main() -> int:
    local = _find_local_harness(Path.cwd().resolve())
    if local is None:
        print("error: repo-local ./harness not found from current directory or parents", file=sys.stderr)
        return 2
    os.execv(str(local), [str(local), *sys.argv[1:]])
    return 127


if __name__ == "__main__":
    raise SystemExit(main())
"""


def _is_installed_global_shim(path: Path) -> bool:
    if not path.exists() or path.is_symlink() or not path.is_file():
        return False
    try:
        return GLOBAL_SHIM_MARKER in path.read_text(encoding="utf-8", errors="replace")[:4096]
    except OSError:
        return False


