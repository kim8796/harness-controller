def _goal_payload_for_backlog(
    record: harness_controller.TargetRecord,
    goal_id: str,
) -> dict[str, object]:
    resolved_goal_id = str(goal_id or "").strip()
    candidates: list[Path] = []
    if resolved_goal_id and resolved_goal_id != "unlinked":
        candidates.append(record.state_root / "goals" / resolved_goal_id / "goal.json")
    try:
        active = harness_goal.load_active_goal(record.state_root)
    except harness_goal.GoalError:
        active = None
    if active is not None:
        candidates.append(active.goal_json)
    seen: set[Path] = set()
    for candidate in candidates:
        if candidate in seen:
            continue
        seen.add(candidate)
        try:
            payload = json.loads(candidate.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(payload, dict):
            continue
        payload_goal_id = str(payload.get("goal_id") or "").strip()
        if resolved_goal_id and resolved_goal_id != "unlinked" and payload_goal_id != resolved_goal_id:
            continue
        return payload
    raise HarnessCliError(f"goal gate verifier backlog has no readable goal payload: {resolved_goal_id or 'unlinked'}")


def _run_goal_gate_verification_transaction(
    record: harness_controller.TargetRecord,
    backlog_id: str,
) -> AutopilotTransaction:
    goal_id = _backlog_goal_id(record, backlog_id)
    goal_payload = _goal_payload_for_backlog(record, goal_id)
    result = harness_production_gate_verifier.verify_goal_gates(
        product_root=record.repo,
        state_root=record.state_root,
        target_id=record.target_id,
        goal_id=str(goal_payload.get("goal_id") or goal_id),
        goal_payload=goal_payload,
        write_operator_waits=True,
    )
    run_id = str(result.get("run_id") or "")
    if not run_id:
        raise HarnessCliError("goal gate verifier did not return a run id")
    completion = harness_controller.complete_sidecar_backlog_with_controller_evidence(
        controller_root=repo_root(),
        record=record,
        backlog_ref=backlog_id,
        run_id=run_id,
        reason="goal gate verifier evidence generated",
        apply=True,
    )
    status = str(result.get("status") or "blocked")
    blocked_gate_ids = [
        str(item)
        for item in result.get("blocked_gate_ids", [])
        if str(item)
    ] if isinstance(result.get("blocked_gate_ids"), list) else []
    print(f"- gate verifier: `{status}`")
    if blocked_gate_ids:
        print(f"- blocked gates: `{', '.join(blocked_gate_ids)}`")
    evidence_path = str(result.get("generated_evidence_path") or "")
    if evidence_path:
        print(f"- gate verifier evidence: `{evidence_path}`")
    print(f"- 완료 처리: `{completion['target_path']}`")
    product_sha = str(result.get("product_commit_sha") or "")
    return AutopilotTransaction(
        "gate-verified",
        run_id,
        backlog_id,
        product_sha,
        product_sha,
        f"goal gate verifier {status}",
    )


def _write_product_version_receipt(
    *,
    record: harness_controller.TargetRecord,
    goal_id: str,
    backlog_id: str,
    run_id: str,
    product_commit_sha: str,
    pr_url: str = "",
    merge_commit_sha: str = "",
    status: str = "integrated",
) -> None:
    if not product_commit_sha:
        return
    try:
        harness_release.write_receipt(
            record.state_root,
            target_id=record.target_id,
            kind="version",
            receipt_id=f"{backlog_id}-{product_commit_sha[:12]}",
            payload={
                "status": status,
                "goal_id": goal_id,
                "backlog_id": backlog_id,
                "run_id": run_id,
                "product_commit_sha": product_commit_sha,
                "pr_url": pr_url,
                "merge_commit_sha": merge_commit_sha,
                "base_branch": record.branch,
                "values_redacted": True,
            },
        )
    except harness_release.ReleaseError as exc:
        if "already exists" not in str(exc):
            raise


def _implementation_failure_message(output: str) -> str:
    lines = [line.rstrip() for line in sanitize_for_outbox(output).splitlines() if line.strip()]
    if not lines:
        return "AI 구현 lane이 실패했습니다."
    detail = "\n".join(lines[-16:])
    return f"AI 구현 lane이 실패했습니다.\n{detail}"


def _run_autopilot_transaction(record: harness_controller.TargetRecord, args: argparse.Namespace) -> AutopilotTransaction:
    selected_item = _target_next_auto_backlog_item(record)
    selected_backlog_id = str(getattr(selected_item, "item_id", "") or "")
    selected_text = _backlog_item_text(record.state_root, selected_item)
    if _backlog_is_goal_gate_verification_task(selected_text):
        return _run_goal_gate_verification_transaction(record, selected_backlog_id)
    summary = harness_controller.find_resumable_target_implementation_evidence(
        controller_root=repo_root(),
        record=record,
        backlog_id=selected_backlog_id,
    )
    if summary:
        run_id = str(summary.get("run_id") or "")
        print(f"- 구현 재개: 기존 uncommitted diff가 `{run_id}` evidence와 일치합니다.")
    else:
        before_evidence = _target_evidence_paths(record)
        buffer = io.StringIO()
        with contextlib.redirect_stdout(buffer):
            rc = command_target_run(
                argparse.Namespace(
                    target=record.target_id,
                    once=False,
                    plan_once=False,
                    execute_once=False,
                    execute_backlog_once=False,
                    implement_backlog_once=True,
                    runner=args.runner,
                    runner_model=args.runner_model,
                    runner_reasoning_effort=args.runner_reasoning_effort,
                    command_template=args.command_template,
                    execution_profile=getattr(args, "execution_profile", "auto"),
                    commit=False,
                    push=False,
                )
            )
        implementation_output = buffer.getvalue().strip()
        if rc != 0:
            if implementation_output:
                print(implementation_output)
            raise HarnessCliError(_implementation_failure_message(implementation_output))
        new_evidence = sorted(_target_evidence_paths(record) - before_evidence)
        if len(new_evidence) != 1:
            if implementation_output:
                print(implementation_output)
            raise HarnessCliError("구현 run id를 정확히 특정하지 못했습니다.")
        run_id = new_evidence[0].parent.name
        summary = harness_controller.find_target_implementation_evidence(
            controller_root=repo_root(),
            record=record,
            run_id=run_id,
        )
    backlog_id = str(summary.get("backlog_id") or "")
    backlog_title = str(summary.get("backlog_title") or "")
    print(f"- 구현 완료: `{run_id}`")
    print(f"- 작업 항목: `{backlog_id}`" + (f" - {backlog_title}" if backlog_title else ""))

    transition = harness_controller.transition_sidecar_backlog(
        controller_root=repo_root(),
        record=record,
        status="completed",
        reason="autopilot implementation accepted",
        run_id=run_id,
        apply=True,
    )
    print(f"- 완료 처리: `{transition['target_path']}`")

    message = _autopilot_commit_message(backlog_id, backlog_title)
    commit = harness_controller.commit_sidecar_backlog_product_diff(
        controller_root=repo_root(),
        record=record,
        run_id=run_id,
        message=message,
        apply=True,
    )
    commit_sha = str(commit.get("product_commit_sha") or "")
    print(f"- product commit: `{commit_sha}`")

    goal_id = _backlog_goal_id(record, backlog_id)
    publication = harness_publication.publish_task_pr(
        controller_root=repo_root(),
        state_root=record.state_root,
        target_repo=record.repo,
        target_id=record.target_id,
        goal_id=goal_id,
        backlog_id=backlog_id,
        run_id=run_id,
        commit_sha=commit_sha,
        base_branch=record.branch,
        title=message,
        body=(
            f"Goal: `{goal_id}`\n\n"
            f"Backlog: `{backlog_id}`\n\n"
            f"Implementation run: `{run_id}`\n\n"
            "Generated by harness goal autopilot.\n"
        )
    )
    if publication.status == "already-in-base":
        print(f"- product branch: `{publication.branch}`")
        print("- product PR: `already in base`")
        _write_product_version_receipt(
            record=record,
            goal_id=goal_id,
            backlog_id=backlog_id,
            run_id=run_id,
            product_commit_sha=commit_sha,
            status="integrated",
        )
        return AutopilotTransaction(
            "merged",
            run_id,
            backlog_id,
            commit_sha,
            commit_sha,
            publication.message,
            publication_branch=publication.branch,
        )
    if publication.status in {"created", "updated"}:
        print(f"- product branch: `{publication.branch}`")
        print(f"- product PR: `{publication.pr_url}`")
        if bool(getattr(args, "auto_merge", False)):
            merge = harness_publication.merge_task_pr(
                controller_root=repo_root(),
                state_root=record.state_root,
                target_repo=record.repo,
                target_id=record.target_id,
                goal_id=goal_id,
                backlog_id=backlog_id,
                run_id=run_id,
                commit_sha=commit_sha,
                branch=publication.branch,
                base_branch=record.branch,
                pr_url=publication.pr_url,
                pending_check_retry_attempts=harness_publication.PENDING_CHECK_RETRY_ATTEMPTS,
                pending_check_retry_delay_seconds=harness_publication.PENDING_CHECK_RETRY_DELAY_SECONDS,
            )
            print(f"- product PR merge: `{merge.status}`")
            if merge.merge_commit_sha:
                print(f"- merge commit: `{merge.merge_commit_sha}`")
            if merge.status == "merged":
                _write_product_version_receipt(
                    record=record,
                    goal_id=goal_id,
                    backlog_id=backlog_id,
                    run_id=run_id,
                    product_commit_sha=merge.local_head_after or merge.merge_commit_sha or commit_sha,
                    pr_url=publication.pr_url,
                    merge_commit_sha=merge.merge_commit_sha,
                    status="integrated",
                )
                return AutopilotTransaction(
                    "merged",
                    run_id,
                    backlog_id,
                    commit_sha,
                    merge.local_head_after or merge.merge_commit_sha or commit_sha,
                    "merged",
                    pr_url=publication.pr_url,
                    publication_branch=publication.branch,
                    merge_commit_sha=merge.merge_commit_sha,
                )
            return AutopilotTransaction(
                merge.status,
                run_id,
                backlog_id,
                commit_sha,
                "",
                merge.message,
                pr_url=publication.pr_url,
                publication_branch=publication.branch,
                merge_commit_sha=merge.merge_commit_sha,
            )
        return AutopilotTransaction(
            "published",
            run_id,
            backlog_id,
            commit_sha,
            commit_sha,
            "completed",
            pr_url=publication.pr_url,
            publication_branch=publication.branch,
        )
    print(f"- product publication: `{publication.status}`")
    print(f"- reason: {publication.message}")
    blocked_status = publication.status if publication.status in {"credential-blocked", "setup-blocked"} else "publication-blocked"
    return AutopilotTransaction(
        blocked_status,
        run_id,
        backlog_id,
        commit_sha,
        "",
        publication.message,
        publication_branch=publication.branch,
    )


