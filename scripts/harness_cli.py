def _wizard_answers_path(args: argparse.Namespace, name: str) -> tuple[Path | None, tempfile.NamedTemporaryFile[str] | None]:
    if getattr(args, "no_wizard", False):
        return None, None
    answers = getattr(args, "answers", None)
    if answers is not None:
        return answers.resolve(), None
    temp_file = _temporary_answers_file(name)
    return Path(temp_file.name), temp_file


def _validate_answers_file(answers_path: Path | None) -> None:
    if answers_path is None:
        return
    if not answers_path.exists():
        raise HarnessCliError(f"bootstrap answers file not found: {answers_path.as_posix()}")
    try:
        payload = json.loads(answers_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise HarnessCliError(f"bootstrap answers file is not valid JSON: {answers_path.as_posix()}") from exc
    if not isinstance(payload, dict):
        raise HarnessCliError("bootstrap answers file must contain a JSON object")
    try:
        harness_bootstrap_wizard.collect_interview(payload)
    except (TypeError, ValueError, KeyError) as exc:
        raise HarnessCliError(f"bootstrap answers file is not a valid starter interview: {answers_path.as_posix()}") from exc


def _preflight_target_env(target_root: Path, *, profile: str) -> None:
    tracked_env = _tracked_env_files(target_root)
    if tracked_env:
        raise HarnessCliError("tracked env files must be untracked before installing harness: " + ", ".join(tracked_env))
    generated_env = target_root / ".env.harness.generated"
    if generated_env.exists() or generated_env.is_symlink():
        raise HarnessCliError("refusing to reuse existing env file: .env.harness.generated")
    if not _profile_enables_telegram(profile):
        return
    destination = _env_destination(target_root)
    if destination.exists() or destination.is_symlink():
        raise HarnessCliError(f"refusing to overwrite existing env file: {destination.name}")


def _commit_path_if_dirty(target_root: Path, path: Path, message: str) -> None:
    relative = path.resolve().relative_to(target_root.resolve()).as_posix()
    status = _git(["status", "--porcelain=v1", "--", relative], cwd=target_root)
    if status.returncode != 0:
        raise HarnessCliError("unable to inspect bootstrap wizard git status")
    if not status.stdout.strip():
        return
    _git_checked(["add", relative], cwd=target_root)
    _git_checked(["commit", "-m", message], cwd=target_root)


def _commit_paths_if_dirty(target_root: Path, paths: Sequence[str], message: str) -> None:
    status = _git(["status", "--porcelain=v1", "--", *paths], cwd=target_root)
    if status.returncode != 0:
        raise HarnessCliError("unable to inspect generated recovery view git status")
    if not status.stdout.strip():
        return
    _git_checked(["add", *paths], cwd=target_root)
    _git_checked(["commit", "-m", message], cwd=target_root)


def _sync_recovery_views(target_root: Path) -> None:
    result = subprocess.run(
        [sys.executable, "scripts/harness_loop.py", "sync-state"],
        cwd=target_root,
        check=False,
        text=True,
        capture_output=True,
        env=_clean_git_env(),
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise HarnessCliError(f"recovery sync failed: {detail}")
    _commit_paths_if_dirty(target_root, RECOVERY_VIEW_PATHS, "chore: sync harness recovery state")


