def _pending_commit_sha(record: harness_controller.TargetRecord, run_id: str) -> str:
    runs_root = record.state_root / "runs" / "harness"
    if not runs_root.exists() or runs_root.is_symlink():
        return ""
    for evidence_path in sorted(runs_root.glob("external-*-backlog-commit-*/generated-evidence.json")):
        try:
            payload = json.loads(evidence_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if (
            payload.get("operation") == "backlog-product-commit"
            and payload.get("applied") is True
            and payload.get("target_id") == record.target_id
            and payload.get("implementation_run_id") == run_id
        ):
            return str(payload.get("product_commit_sha") or "")
    return ""


def _retry_pending_publication(
    *,
    record: harness_controller.TargetRecord,
    pending: Mapping[str, object],
    auto_merge: bool = False,
) -> Mapping[str, object]:
    backlog_id = str(pending.get("backlog_id") or "")
    run_id = str(pending.get("run_id") or "")
    commit_sha = _pending_commit_sha(record, run_id)
    if not backlog_id or not run_id or not commit_sha:
        return {
            "status": "publication-blocked",
            "backlog_id": backlog_id,
            "run_id": run_id,
            "message": "pending publication is missing backlog/run/commit evidence",
        }
    goal_id = _backlog_goal_id(record, backlog_id)
    title = _autopilot_commit_message(backlog_id, str(pending.get("backlog_title") or ""))
    publication = harness_publication.publish_task_pr(
        controller_root=repo_root(),
        state_root=record.state_root,
        target_repo=record.repo,
        target_id=record.target_id,
        goal_id=goal_id,
        backlog_id=backlog_id,
        run_id=run_id,
        commit_sha=commit_sha,
        base_branch=record.branch,
        title=title,
        body=(
            f"Goal: `{goal_id}`\n\n"
            f"Backlog: `{backlog_id}`\n\n"
            f"Implementation run: `{run_id}`\n\n"
            "Generated by harness pending publication retry.\n"
        ),
    )
    result: dict[str, object] = {
        "status": publication.status,
        "backlog_id": backlog_id,
        "run_id": run_id,
        "commit_sha": commit_sha,
        "branch": publication.branch,
        "base": publication.base,
        "pr_url": publication.pr_url,
        "message": publication.message,
    }
    if publication.status in {"created", "updated"} and auto_merge:
        merge = harness_publication.merge_task_pr(
            controller_root=repo_root(),
            state_root=record.state_root,
            target_repo=record.repo,
            target_id=record.target_id,
            goal_id=goal_id,
            backlog_id=backlog_id,
            run_id=run_id,
            commit_sha=commit_sha,
            branch=publication.branch,
            base_branch=record.branch,
            pr_url=publication.pr_url,
            pending_check_retry_attempts=harness_publication.PENDING_CHECK_RETRY_ATTEMPTS,
            pending_check_retry_delay_seconds=harness_publication.PENDING_CHECK_RETRY_DELAY_SECONDS,
        )
        result.update(
            {
                "status": merge.status,
                "merge_commit_sha": merge.merge_commit_sha,
                "message": merge.message,
            }
        )
    return result


