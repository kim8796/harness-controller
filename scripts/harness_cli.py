def _render_bootstrap_drafts(run_dir: Path) -> Path:
    interview = harness_bootstrap_wizard._load_interview(run_dir)
    drafts_dir = harness_bootstrap_wizard.write_drafts(run_dir, harness_bootstrap_wizard.build_drafts(interview))
    return drafts_dir


def _bootstrap_manifest_paths(run_dir: Path) -> list[Path]:
    manifest_path = run_dir / "bootstrap-drafts-manifest.json"
    if not manifest_path.exists():
        raise HarnessCliError("bootstrap drafts manifest missing after render")
    payload = json.loads(manifest_path.read_text(encoding="utf-8"))
    files = payload.get("files")
    if not isinstance(files, list):
        raise HarnessCliError("invalid bootstrap drafts manifest")
    return [Path(str(item.get("path") or "")) for item in files]


def _preflight_bootstrap_overwrites(target_root: Path, run_dir: Path, *, force_existing: bool) -> None:
    if force_existing:
        return
    templates = _starter_placeholder_templates(target_root)
    conflicts: list[str] = []
    for relative_path in _bootstrap_manifest_paths(run_dir):
        destination = target_root / relative_path
        if not destination.exists():
            continue
        if relative_path in templates and destination.read_text(encoding="utf-8", errors="replace") == templates[relative_path]:
            continue
        conflicts.append(relative_path.as_posix())
    if conflicts:
        raise HarnessCliError(
            "bootstrap apply would overwrite non-placeholder files; pass --force-existing after reviewing: "
            + ", ".join(conflicts)
        )


