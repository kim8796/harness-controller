def _write_telegram_env(target_root: Path) -> Path:
    destination = _env_destination(target_root)
    if destination.exists():
        raise HarnessCliError(f"refusing to overwrite existing env file: {destination.name}")
    if destination.is_symlink():
        raise HarnessCliError(f"refusing to write env through symlink: {destination.name}")
    signing_key = _strong_signing_key()
    lines = [
        ENV_GENERATED_HEADER,
        f"# Created: {datetime.now().isoformat(timespec='seconds')}",
        "",
        "HARNESS_TELEGRAM_BRIDGE_ENABLED=true",
        "# HARNESS_TELEGRAM_BOT_TOKEN=<bot-token>",
        "# HARNESS_TELEGRAM_ADMIN_CHAT_ID=<admin-chat-id>",
        "# HARNESS_TELEGRAM_OPERATOR_USER_IDS=<telegram-numeric-user-id>",
        "",
        "HARNESS_RELAY_ENABLED=true",
        f"HARNESS_RELAY_REPO_ID={_repo_id_for(target_root)}",
        f"HARNESS_RELAY_SIGNING_KEY={signing_key}",
        "HARNESS_RELAY_TTL_SECONDS=604800",
        "# UPSTASH_REDIS_REST_URL=<upstash-rest-url>",
        "# UPSTASH_REDIS_REST_TOKEN=<upstash-rest-token>",
        "",
    ]
    destination.write_text("\n".join(lines), encoding="utf-8")
    return destination


def _start_wizard_for_existing_repo(
    *,
    source_root: Path,
    target_root: Path,
    answers_path: Path | None,
) -> Path | None:
    if answers_path is None:
        return None
    command = [
        sys.executable,
        str(source_root / "scripts" / "harness_bootstrap_wizard.py"),
        "start",
        "--target",
        str(target_root),
        "--answers",
        str(answers_path),
    ]
    result = subprocess.run(command, check=False, text=True, capture_output=True, env=_clean_git_env())
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise HarnessCliError(f"bootstrap wizard start failed: {detail}")
    output = result.stdout.strip().splitlines()
    return Path(output[-1]).resolve() if output else None


def command_new(args: argparse.Namespace) -> int:
    source_root = repo_root()
    target = _target_path(args.target)
    name = args.name or target.name
    profile = _selected_profile(args)
    answers_path, temp_answers = _wizard_answers_path(args, name)
    try:
        _validate_answers_file(answers_path)
        result = harness_starter_install.create_project(
            source_root=source_root,
            target=target,
            name=name,
            apply=not args.dry_run,
            include_policy=args.include_policy,
            telegram_operator_bridge=_profile_enables_telegram(profile),
            force_existing=args.force_existing,
            start_wizard=answers_path is not None,
            wizard_answers=answers_path,
        )
        env_path: Path | None = None
        if result.applied and result.wizard_run is not None:
            _commit_path_if_dirty(result.target_root, result.wizard_run, "chore: start harness bootstrap interview")
        if result.applied:
            _sync_recovery_views(result.target_root)
        if result.applied and _profile_enables_telegram(profile):
            env_path = _write_telegram_env(result.target_root)
        _print_completion(
            CommandResult(
                target_root=result.target_root,
                receipt=result.install_receipt,
                wizard_run=result.wizard_run,
                env_path=env_path,
                applied=result.applied,
                profile=profile,
            )
        )
        return 0
    except harness_starter_install.InstallerError as exc:
        print(f"error: {exc}")
        return 2
    except HarnessCliError as exc:
        print(f"error: {exc}")
        return 2
    finally:
        if temp_answers is not None:
            temp_name = temp_answers.name
            temp_answers.close()
            Path(temp_name).unlink(missing_ok=True)


def command_init(args: argparse.Namespace) -> int:
    source_root = repo_root()
    target_root = _target_path(args.target)
    name = args.name or target_root.name
    profile = _selected_profile(args)
    answers_path, temp_answers = _wizard_answers_path(args, name)
    try:
        _validate_answers_file(answers_path)
        validated = harness_starter_install.validate_target(source_root, target_root)
        _preflight_target_env(validated, profile=profile)
        plan = harness_starter_install.build_install_plan(
            source_root=source_root,
            target_root=validated,
            include_policy=args.include_policy,
            telegram_operator_bridge=_profile_enables_telegram(profile),
            force_existing=args.force_existing,
        )
        if plan.conflicts:
            print(harness_starter_install.render_plan(plan), end="")
            return 2
        receipt: Path | None = None
        wizard_run: Path | None = None
        env_path: Path | None = None
        if not args.dry_run:
            receipt = harness_starter_install.apply_install_plan(plan)
            wizard_run = _start_wizard_for_existing_repo(
                source_root=source_root,
                target_root=validated,
                answers_path=answers_path,
            )
            if _profile_enables_telegram(profile):
                env_path = _write_telegram_env(validated)
        else:
            print(harness_starter_install.render_plan(plan), end="")
        _print_completion(
            CommandResult(
                target_root=validated,
                receipt=receipt,
                wizard_run=wizard_run,
                env_path=env_path,
                applied=not args.dry_run,
                profile=profile,
            )
        )
        return 0
    except harness_starter_install.InstallerError as exc:
        print(f"error: {exc}")
        return 2
    except HarnessCliError as exc:
        print(f"error: {exc}")
        return 2
    finally:
        if temp_answers is not None:
            temp_name = temp_answers.name
            temp_answers.close()
            Path(temp_name).unlink(missing_ok=True)


