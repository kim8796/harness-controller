def _build_verify_payload(target_root: Path, *, loop_ready: bool) -> dict[str, object]:
    missing = _verify_required_files(target_root)
    status = _git(["status", "--porcelain=v1"], cwd=target_root)
    dirty = status.stdout.strip().splitlines() if status.returncode == 0 else ["<unable to inspect>"]
    tracked_env = _tracked_env_files(target_root)
    env_values = harness_env.read_harness_env_files(target_root, include_process_env=True)
    telegram_ready = harness_env.telegram_relay_readiness(env_values)
    docs_ready = _docs_ready(target_root)
    executable_backlog = _has_executable_backlog(target_root)
    bootstrap_approved = _bootstrap_approved(target_root)
    blockers: list[str] = []
    if missing:
        blockers.append("required-files-missing")
    if dirty:
        blockers.append("git-dirty")
    if tracked_env:
        blockers.append("tracked-env-files")
    if loop_ready and not bootstrap_approved:
        blockers.append("bootstrap-not-applied")
    if loop_ready and not all(docs_ready.values()):
        blockers.append("bootstrap-docs-missing")
    if loop_ready and not executable_backlog:
        blockers.append("no-executable-backlog")
    return {
        "schema_version": 1,
        "target": target_root.as_posix(),
        "mode": "loop-ready" if loop_ready else "install",
        "ok": not blockers,
        "blockers": blockers,
        "required_files": {"ok": not missing, "missing": missing},
        "git": {"clean": not dirty, "dirty_paths": dirty},
        "tracked_env_files": tracked_env,
        "telegram_relay": telegram_ready,
        "telegram_relay_live_ready": all(telegram_ready.values()),
        "bootstrap": {
            "approved": bootstrap_approved,
            "docs_ready": docs_ready,
            "executable_backlog": executable_backlog,
        },
    }


def _next_verify_command(payload: Mapping[str, object], *, loop_ready: bool) -> str:
    blockers = set(payload.get("blockers") or [])
    if "git-dirty" in blockers or "tracked-env-files" in blockers:
        return "git status --short"
    if "bootstrap-not-applied" in blockers or "bootstrap-docs-missing" in blockers or "no-executable-backlog" in blockers:
        return "./harness complete-setup --apply"
    if "required-files-missing" in blockers:
        return "./harness verify"
    return "./harness run --once" if loop_ready else "./harness verify --loop-ready"


