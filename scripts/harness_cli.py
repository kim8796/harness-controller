def _latest_bootstrap_run(target_root: Path) -> Path:
    runs_root = target_root / "runs" / "harness"
    candidates = [
        path
        for path in runs_root.glob("*")
        if path.is_dir() and (path / "bootstrap-interview.json").exists()
    ]
    if not candidates:
        raise HarnessCliError("bootstrap interview run 이 없습니다. 먼저 ./harness new/init 을 --no-wizard 없이 실행하세요.")
    return max(candidates, key=lambda path: (path.stat().st_mtime, path.name)).resolve()


def _resolve_bootstrap_run(target_root: Path, raw_run: Path | None) -> Path:
    run_dir = _latest_bootstrap_run(target_root) if raw_run is None else _target_path(raw_run)
    try:
        run_dir.resolve().relative_to((target_root / "runs" / "harness").resolve())
    except ValueError as exc:
        raise HarnessCliError("bootstrap run must be inside target runs/harness") from exc
    if not (run_dir / "bootstrap-interview.json").exists():
        raise HarnessCliError(f"missing bootstrap interview: {run_dir.as_posix()}")
    return run_dir.resolve()


