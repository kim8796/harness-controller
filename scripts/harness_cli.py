    print(f"- git clean: {'yes' if git_state['clean'] else 'no'}")
    tracked_env = payload["tracked_env_files"]
    print(f"- tracked env 파일: {'none' if not tracked_env else ', '.join(tracked_env)}")
    if loop_ready:
        docs_ready = bootstrap["docs_ready"]
        missing_docs = [name for name, ok in docs_ready.items() if not ok]
        print(f"- bootstrap 적용: {'yes' if bootstrap['approved'] else 'no'}")
